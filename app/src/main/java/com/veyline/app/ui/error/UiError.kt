package com.veyline.app.ui.error

/**
 * UI 层使用的通用错误类型。
 *
 * 本类型不照搬网络层的完整错误分类，只保留大多数页面在展示错误时需要区分的情况。
 * 同一种错误可以根据页面当前状态显示为全屏错误、Snackbar、Toast 或其他形式，具体采用
 * 哪种展示方式不属于本类型的职责。
 *
 * 表单字段验证、登录失效，以及会改变页面处理流程的特殊业务错误，应由相应页面或全局
 * 机制单独处理，不应强行转换为通用错误。
 */
sealed interface UiError {

    /**
     * 请求因网络连接问题未能完成。
     *
     * 常见场景包括设备断网、飞行模式、DNS 解析失败、连接超时或网络切换导致连接中断。
     * 本类型不表示设备一定处于离线状态，只表示请求未能建立或维持有效连接。
     */
    data object Connection : UiError

    /**
     * 请求因技术问题或未识别的错误而无法完成。
     *
     * 常见场景包括未由具体业务单独处理的 HTTP 404、HTTP 503、响应解析失败、API 数据
     * 不符合客户端约定，以及没有预定义处理方式的非成功业务 code。
     *
     * 具体原因只用于日志和内部诊断。UI 应展示统一的技术错误文案，不直接暴露状态码、
     * 异常信息或未经确认的服务端消息。
     */
    data object Technical : UiError

    /**
     * 已由具体业务转换并确认可以直接展示给用户的错误。
     *
     * 例如详情接口返回预定义的“内容不存在”错误码时，可以转换为“内容不存在或已删除”；
     * 限流错误也可以转换为“请求过于频繁，请稍后再试”。
     *
     * 未识别、内容为空或可能包含内部诊断信息的服务端消息不得使用本类型，应降级为
     * [Technical]。
     *
     * @property message 已确认适合直接展示给用户的错误文案。
     */
    data class DisplayReady(
        val message: String,
    ) : UiError
}
